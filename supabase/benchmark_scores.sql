-- IYS Human Benchmark：成绩表 + 排行榜
-- 在 Supabase 控制台 → SQL Editor 里整段执行一次即可。

create table if not exists public.benchmark_scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  test text not null check (test in ('reaction', 'click', 'typing')),
  value numeric not null,
  detail jsonb,
  created_at timestamptz not null default now()
);

create index if not exists benchmark_scores_board
  on public.benchmark_scores (test, value);

alter table public.benchmark_scores enable row level security;

-- 排行榜需要读所有人的成绩（只有名字和分数，没有邮箱）
drop policy if exists "read own scores" on public.benchmark_scores;
drop policy if exists "read all scores" on public.benchmark_scores;
create policy "read all scores" on public.benchmark_scores
  for select using (true);

-- 只能以自己的身份写入
drop policy if exists "insert own scores" on public.benchmark_scores;
create policy "insert own scores" on public.benchmark_scores
  for insert with check (auth.uid() = user_id);

-- 只能删自己的
drop policy if exists "delete own scores" on public.benchmark_scores;
create policy "delete own scores" on public.benchmark_scores
  for delete using (auth.uid() = user_id);

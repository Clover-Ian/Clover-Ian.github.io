-- 7. 服务端发号 + 在线校验（更安全的方案）
--    IYS Pro 发号时把 key 写进 issued_keys，App 每次校验都问服务器。
--    这样即使有人从 App 里抠出签名密钥，自己造的 key 也不在库里，一律无效。
-- ============================================================

create table if not exists public.issued_keys (
    license_key text primary key,
    products    text[] not null default '{}',
    days        int    not null default 30,
    note        text   not null default '',
    revoked     boolean not null default false,
    created_at  timestamptz not null default now()
);

alter table public.issued_keys enable row level security;

-- 发号登记（IYS Pro 用口令调用）
create or replace function public.register_key(
    passcode text,
    key_text text,
    apps text[],
    days_count int,
    note_text text default ''
)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
    if passcode <> 'iys-pro-8074ed5a77cfe853' then
        return false;
    end if;

    insert into public.issued_keys (license_key, products, days, note)
    values (upper(key_text), apps, days_count, coalesce(note_text, ''))
    on conflict (license_key) do update
        set products = excluded.products,
            days     = excluded.days,
            note     = case when excluded.note = ''
                            then public.issued_keys.note
                            else excluded.note end;

    return true;
end;
$$;

grant execute on function public.register_key(text, text, text[], int, text) to anon, authenticated;

-- 作废一把 key
create or replace function public.revoke_key(passcode text, key_text text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
begin
    if passcode <> 'iys-pro-8074ed5a77cfe853' then
        return false;

-- 激活
create or replace function public.activate_license(candidate text, app text default 'archiver')
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    me    uuid := auth.uid();
    clean text := upper(regexp_replace(candidate, '\s', '', 'g'));
    owner uuid;
    mine  boolean;
begin
    if me is null then return 'sign_in_required'; end if;
    if clean is null or clean = '' then return 'invalid'; end if;

    select user_id into owner
      from public.license_activations
     where license_key = clean
     order by activated_at
     limit 1;

    if owner is not null and owner <> me then return 'taken'; end if;

    select exists (
        select 1 from public.license_activations
         where license_key = clean and product = app and user_id = me
    ) into mine;

    if mine then return 'already_yours'; end if;

    insert into public.license_activations (license_key, user_id, product)
    values (clean, me, app)
    on conflict (license_key, product) do nothing;

    return 'activated';
end;
$$;

grant execute on function public.activate_license(text, text) to authenticated;

